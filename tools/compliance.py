#!/usr/bin/env python3
"""Requirement-to-test compliance report.

Reads requirement IDs (R-AREA-n) from docs/SPEC.md and invariant IDs (INV-n) from CLAUDE.md, finds
`@custom:requirement` and `@custom:invariant` tags in test/**/*.sol, writes docs/COMPLIANCE.md and prints a summary.
With --check, exits non-zero if any SPEC requirement has no test. Until the suite is complete it only reports.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ = re.compile(r"\*\*(R-[A-Z]+-\d+)\*\*")
INV = re.compile(r"\*\*(INV-\d+)\*\*")
TAG = re.compile(r"@custom:(requirement|invariant)[ \t]+([^\n*]+)")
ID = re.compile(r"(R-[A-Z]+-\d+|INV-\d+)")
FUNC = re.compile(r"function\s+(\w+)\s*\(")


def collect_ids(path, pattern):
    return sorted(set(pattern.findall(path.read_text(encoding="utf-8"))), key=_key)


def _key(i):
    parts = i.split("-")
    return (parts[0], parts[1] if parts[0] == "R" else "", int(parts[-1]))


def collect_tests():
    """Map ID -> sorted list of 'File:test' (or 'File' for contract-level tags)."""
    mapping = {}
    for f in sorted((ROOT / "test").rglob("*.sol")):
        text = f.read_text(encoding="utf-8")
        for m in TAG.finditer(text):
            ids = ID.findall(m.group(2))
            rest = text[m.end():]
            nxt = re.search(r"\b(function|contract|library)\s+(\w+)", rest)
            name = f.name
            if nxt and nxt.group(1) == "function":
                name = f"{f.name}:{nxt.group(2)}"
            for i in ids:
                mapping.setdefault(i, set()).add(name)
    return {k: sorted(v) for k, v in mapping.items()}


def main():
    reqs = collect_ids(ROOT / "docs" / "SPEC.md", REQ)
    invs = collect_ids(ROOT / "CLAUDE.md", INV)
    tests = collect_tests()
    lines = ["# Compliance matrix", "", "Generated by `tools/compliance.py` from `@custom:requirement` and "
             "`@custom:invariant` tags in `test/`. Do not edit by hand.", ""]
    missing = []
    for title, ids in (("Requirements (docs/SPEC.md)", reqs), ("Invariants (CLAUDE.md §8.2)", invs)):
        lines += [f"## {title}", "", "| ID | Tests |", "|---|---|"]
        for i in ids:
            t = tests.get(i)
            if not t:
                missing.append(i)
            lines.append(f"| {i} | {', '.join(f'`{x}`' for x in t) if t else '_none yet_'} |")
        lines.append("")
    unknown = sorted(set(tests) - set(reqs) - set(invs), key=_key)
    if unknown:
        lines += ["## Tags with no matching requirement", "", ", ".join(unknown), ""]
    (ROOT / "docs" / "COMPLIANCE.md").write_text("\n".join(lines), encoding="utf-8")
    total = len(reqs) + len(invs)
    print(f"{total - len(missing)}/{total} IDs have at least one test; {len(missing)} without.")
    if unknown:
        print("Tags with no matching requirement:", ", ".join(unknown))
    if "--check" in sys.argv and (missing or unknown):
        sys.exit(1)


if __name__ == "__main__":
    main()
